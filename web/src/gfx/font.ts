export function get_glyph(ch: string, variant?: "name_entry"): readonly string[] {
  return (variant === "name_entry" ? name_entry_glyphs[ch] : undefined) ?? GLYPHS[ch] ?? GLYPHS[" "];
}

export function measure(text: string, scale: number): number {
  const length = Array.from(text).length;
  return length === 0 ? 0 : (length * ADVANCE - 1) * scale;
}

// Merge lit pixels into horizontal runs. Rotated text keeps the canvas transform;
// axis-aligned text snaps its origin and pixel dimensions to device pixels.
export function draw_text(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, scale: number): void {
  const m = ctx.getTransform();
  const snap = m.b === 0 && m.c === 0;
  let pixel_w = scale;
  let pixel_h = scale;
  ctx.save();
  if (snap) {
    x = Math.round(m.e + m.a * x);
    y = Math.round(m.f + m.d * y);
    pixel_w = Math.max(1, Math.round(Math.abs(scale * m.a))) * (m.a < 0 ? -1 : 1);
    pixel_h = Math.max(1, Math.round(Math.abs(scale * m.d))) * (m.d < 0 ? -1 : 1);
    ctx.setTransform(1, 0, 0, 1, 0, 0);
  }
  let char_index = 0;
  for (const ch of text) {
    const glyph = get_glyph(ch);
    for (let row = 0; row < GLYPH_H; row++) {
      let col = 0;
      while (col < GLYPH_W) {
        if (glyph[row][col] !== "#") { col++; continue; }
        const start = col;
        while (col < GLYPH_W && glyph[row][col] === "#") col++;
        ctx.fillRect(x + (char_index * ADVANCE + start) * pixel_w, y + row * pixel_h, (col - start) * pixel_w, pixel_h);
      }
    }
    char_index++;
  }
  ctx.restore();
}
